export function useTranslation(lang: Lang) {
  const t = (key: string): string => {
    const tr = translations[lang] as Record<string, string>;
    const en = translations.en as Record<string, string>;
    return tr[key] ?? en[key] ?? key;
  };
  return { t };
}
